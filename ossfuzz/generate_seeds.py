def u16(value):
    return struct.pack("<H", value & 0xFFFF)


def u32(value):
    return struct.pack("<I", value & 0xFFFFFFFF)


def write(path, data):
    with open(path, "wb") as file_handle:
        file_handle.write(data)
    print(f"wrote {path} ({len(data)} bytes)")


# ---------------------------------------------------------------------------
# AGDB body ( file header + database header + volume entry + device path )
# ---------------------------------------------------------------------------
def agdb_body(total_size, source_entry_size=0, number_of_sources=0):
    body = b""
    body += b"\x0e" + b"\x00" * 3  # [0..4)  file header signature 0x0e
    body += u32(total_size)  # [4..8)  data size
    body += u32(80)  # [8..12) file header size ( 12 + 68 )
    body += u32(0)  # [12..16) database type
    body += u32(56)  # [16..20) volume information entry size
    body += u32(56)  # [20..24) file information entry size
    body += u32(source_entry_size)  # [24..28) source information entry size
    body += u32(0)  # [28..32) file information sub entry type1 size
    body += u32(0)  # [32..36) file information sub entry type2 size
    body += b"\x00" * 16  # [36..52) remaining database parameters
    body += u32(1)  # [52..56) number of volumes
    body += u32(0)  # [56..60) number of files
    body += u32(0)  # [60..64) unknown3
    body += u32(number_of_sources)  # [64..68) number of sources
    body += u32(0)  # [68..72) unknown4
    body += u32(0)  # [72..76) unknown5
    body += b"\x00" * 4  # [76..80) database header tail

    # volume entry ( 56 bytes ) + UTF-16 device path "0:" ( 6 bytes )
    body += u32(0) * 2  # [80..88) volume unknown1, unknown2
    body += u32(0)  # [88..92) number of files
    body += u32(0)  # [92..96) unknown3
    body += b"\x00" * 8  # [96..104) unknown4
    body += b"\x01" + b"\x00" * 7  # [104..112) creation time
    body += b"\x07" + b"\x00" * 3  # [112..116) serial number 0x07
    body += u32(0) * 2  # [116..124) unknown5, unknown6
    body += u16(2)  # [124..126) device path number of characters
    body += u16(0)  # [126..128) unknown7
    body += b"\x00" * 8  # [128..136) unknown9
    body += "0:".encode("utf-16-le") + b"\x00\x00"  # [136..142) device path "0:"

    assert len(body) == 142
    return body


# ---------------------------------------------------------------------------
# LZNT1
# ---------------------------------------------------------------------------
def lznt1_chunk(symbols):
    """Header + stream for a valid LZNT1 chunk decoding `symbols`.

    A symbol is ( 0, byte ) for a literal or ( 1, ( offset, size ) )
    for a tuple.

    The stream is interleaved: for each group of up to 8 symbols a
    flag byte ( bit 0 = first symbol in the group, set for a tuple )
    is followed by the group's symbol payloads in order.
    """
    body = b""
    for group_start in range(0, len(symbols), 8):
        group = symbols[group_start : group_start + 8]
        flag = 0
        payload = b""

        for bit, symbol in enumerate(group):
            if symbol[0] == 1:
                flag |= 1 << bit
                offset, size = symbol[1]
                payload += u16(((offset - 1) << 12) | (size - 3))
            else:
                payload += bytes([symbol[1]])
        body += bytes([flag]) + payload

    data = u16(0x8000 | (len(body) - 1)) + body

    assert len(data) == (struct.unpack("<H", data[:2])[0] & 0x0FFF) + 3
    return data


