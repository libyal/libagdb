# Seed files for file_fuzzer
# ---------------------------------------------------------------------------
def make_file_seeds(out_dir):
    write(f"{out_dir}/file.1", b"\x05\x00\x00\x00" + u32(8))

    body = agdb_body(144)
    write(f"{out_dir}/file.2", body + b"\x00\x00")

    # 1 volume ( 56-byte entry + 6-byte path ), 8-byte alignment, and 1 source:
    # entry size 100, ASCII executable filename "abc" at entry offset 44
    total_size = 80 + 56 + 6 + 2 + 100  # = 244 ( 2-byte alignment padding )
    body = agdb_body(total_size, source_entry_size=100, number_of_sources=1)
    padding = b"\x00" * 2  # [142..144) 8-byte alignment
    src = u32(0) * 11  # [144..188) unknowns / name hash
    src += b"abc\x00" + b"\x00" * 12  # [188..204) executable filename "abc"
    src += u32(0) * 10  # [204..244) trailing unknowns
    assert len(src) == 100
    write(f"{out_dir}/file.3", body + padding + src)

    # Windows Vista ( MEMO ) compressed AGDB file with a hand-encoded
    # LZNT1 chunk decoding a full AGDB body
    # ( 1 volume, device path "0:" ), 0 sources
    total_size = 160
    body = agdb_body(total_size)

    # symbols: 142 body literals, 9 zero literals, 1 tuple ( offset 1, size 9 ).
    # Output = 151 literals + 9 tuple bytes = 160 = total_size
    symbols = [(0, byte) for byte in body]
    symbols += [(0, 0x00)] * 9
    symbols.append((1, (1, 9)))  # copy 9 bytes from offset 1
    assert sum(1 for symbol in symbols if symbol[0] == 0) == 151
    assert len(symbols) == 152
    assert 151 + 9 == total_size

    compressed_file = b"MEMO" + u32(total_size) + lznt1_chunk(symbols)
    write(f"{out_dir}/file.4", compressed_file)


# ---------------------------------------------------------------------------
# Seed files for compressed_block_fuzzer
# ---------------------------------------------------------------------------
def block_input(flavor, expected_size, stream):
    return bytes([flavor]) + u32(expected_size) + stream


def make_block_seeds(out_dir):
    # LZNT1 block decoding "ABCDEFGH" ( 8 bytes )
    symbols = [(0, char) for char in b"ABCDEFGH"]
    lznt1_small = lznt1_chunk(symbols)
    assert len(lznt1_small) == 11  # 1 flag byte + 8 literals, 2-byte header
    write(f"{out_dir}/compressed_block.1", block_input(0, 8, lznt1_small))

    huffman_small = base64.b64decode(HUFFMAN_STREAM_SMALL_B64)
    assert len(huffman_small) == 277
    write(f"{out_dir}/compressed_block.2", block_input(1, 26, huffman_small))
    write(f"{out_dir}/compressed_block.3", block_input(2, 26, huffman_small))
    write(f"{out_dir}/compressed_block.4", block_input(3, 26, huffman_small))

    lznt1_large = base64.b64decode(LZNT1_STREAM_B64)
    assert len(lznt1_large) == 4135
    write(f"{out_dir}/compressed_block.5", block_input(0, 7640, lznt1_large))

    huffman_large = base64.b64decode(HUFFMAN_STREAM_LARGE_B64)
    assert len(huffman_large) == 74358
    write(f"{out_dir}/compressed_block.6", block_input(1, 603246, huffman_large))


